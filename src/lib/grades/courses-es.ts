/** A lab graded on weekly experiments (WE) and the in-person demonstration (ID). */
function demonstrationLab(
  course: Pick<GradeCourse, 'id' | 'level' | 'name' | 'code'>,
  eligibility: string,
): GradeCourse {
  return {
    ...course,
    program: 'es',
    components: [
      { key: 'WE', label: 'Weekly experiments (online labs)', max: 100 },
      { key: 'ID', label: 'In-person demonstration', max: 100 },
    ],
    final: null,
    formula: '0.4*WE + 0.6*ID',
    display: 'T = 0.4(WE) + 0.6(ID)',
    bonusMax: 0,
    conditions: [{ expr: 'WE >= 40', text: 'Weekly experiments at least 40' }],
    notes: [eligibility, IN_CAMPUS_LAB],
  }
}

/** An in-person-only lab graded on attendance and the experiment with viva. */
function attendanceLab(course: Pick<GradeCourse, 'id' | 'level' | 'name' | 'code'>): GradeCourse {
  return {
    ...course,
    program: 'es',
    components: [
      { key: 'Attendance', label: 'Attendance (100 if you attended)', max: 100 },
      { key: 'LabViva', label: 'Lab experiment and viva', max: 100 },
    ],
    final: null,
    formula: '0.2*Attendance + 0.8*LabViva',
    display: 'T = 0.2(Attendance) + 0.8(Lab experiment and Viva)',
    bonusMax: 0,
    conditions: [],
    notes: ['There are no online labs: the lab is in person only.', IN_CAMPUS_LAB],
  }
}

