const SIT_END_TERM =
  'To sit the end term: average of your best 5 of the first 7 weekly assignments at least 40, and at least one quiz attended.'
const FOUNDATION_GAA =
  'Weekly assignments carry no weight in T this term, but about 10 marks of quiz and end-term questions come from them.'

/** A Foundation course graded only on the two quizzes and the end term. */
function foundationQuizCourse(
  id: string,
  name: string,
  code: string,
  extra: Partial<GradeCourse> = {},
): GradeCourse {
  return {
    id,
    program: 'ds',
    level: 'foundation',
    name,
    code,
    components: [QZ1, QZ2],
    final: END_TERM,
    formula: QUIZ_FORMULA,
    display: QUIZ_DISPLAY,
    bonusMax: 0,
    conditions: [],
    notes: [SIT_END_TERM, FOUNDATION_GAA],
    ...extra,
  }
}

